#!/usr/bin/env node
// Bring the questionnaire skill's own copies up to date with the world. Run as `npm run sync:skill`.
//
// The skill (skills/patrick-world-init/) is installed on its own, into whichever coding agent
// its owner uses, on machines this repository may not be on. So it cannot import from src/,
// and it cannot count on a Node new enough to run TypeScript. It carries:
//
//   scripts/definition.mjs   src/world/definition.ts with its types stripped: plain JavaScript
//   vocabulary.json          the map's regions and methods
//
// src/skill.test.ts fails when either has fallen behind, and says to run this.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { catalogue } from '../src/world/fixtures/catalogue.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const skill = resolve(root, 'skills', 'patrick-world-init');

const source = readFileSync(resolve(root, 'src', 'world', 'definition.ts'), 'utf8');
// The first line names the source it was made from, by hash. The test checks that hash.
const header = `// GENERATED by \`npm run sync:skill\` from src/world/definition.ts (sha256 ${createHash('sha256').update(source).digest('hex')}). Do not edit.\n`;
writeFileSync(resolve(skill, 'scripts', 'definition.mjs'), header + stripTypeScriptTypes(source));

/** The part of the catalogue a person choosing words needs. Kept in step with src/skill.test.ts. */
const vocabulary = {
  regions: catalogue.regions.map((r) => ({ id: r.id, name: r.name, note: r.note })),
  methods: catalogue.methods.map((m) => ({ id: m.id, name: m.name, family: m.family })),
};
writeFileSync(resolve(skill, 'vocabulary.json'), `${JSON.stringify(vocabulary, null, 2)}\n`);
console.log('skill: definition.mjs and vocabulary.json are in step with the world.');
